/* civ4_wbs_core.js -- viewer tile grid -> Civ4 BtS WorldBuilder save (.CivBeyondSwordWBSave)
 * Kept in sync with the inlined copy in index.html; validated by civ4_wbs_test.js.
 * (No node/python on this machine: run the test by pasting core+test into the browser console
 * or the Claude Browser pane -- both files are dual node/browser.)
 *
 * Input is the game-agnostic viewer representation (north-origin, same as the classifier):
 *   grid[gy][gx], gy=0 NORTH: { terrain:'TERRAIN_*', plot:0|1|2|3 (peak/hills/flat/water),
 *                               feature?:'FEATURE_*', fv?:int, bonus?:'BONUS_*' (special tiles) }
 *   rivers: {nof,wof} from rivers_core.reachesToEdges, keyed 'gr,gx' with gr=0 NORTH.
 * Civ4 is south-origin; the flip grid[(H-1)-civY][gx] happens only here, at serialize time.
 *
 * Format grounded in the vanilla PublicMaps/Europe.CivBeyondSwordWBSave (Version=11):
 *   - plots are written column-major (x outer, y inner), one BeginPlot/EndPlot per tile,
 *     TerrainType + PlotType always present, FeatureType before them when set.
 *   - a map with no placed starts ships placeholder players (LeaderType=NONE, CivType=NONE,
 *     RandomStartLocation=true) and NO team blocks -- the game then seats any civ count.
 *   - a map WITH placed starts must still define all 18 civ slots (real ones first, the rest
 *     LeaderType=NONE) plus 18 teams -- BtS reads every slot at init, and undefined ones crash it.
 *   - a tile may carry an optional bonus (t.bonus='BONUS_*') from a special-tile rule; it is written
 *     as a BonusType line. 'Randomize Resources=true' still scatters the rest and keeps ours, because
 *     Civ4's addBonuses() skips plots that already have a bonus.
 *   - regional maps do not wrap (Europe: wrap X=0); pass wrapX:1 only for full-360 windows.
 *   - output uses CRLF line endings: Civ4's parser is Windows-native and CTDs on LF-only files.
 */
(function (root) {
  "use strict";

  function worldSizeFor(W, H) {
    const n = W * H;
    if (n <= 40 * 24) return "WORLDSIZE_DUEL";
    if (n <= 56 * 36) return "WORLDSIZE_TINY";
    if (n <= 66 * 44) return "WORLDSIZE_SMALL";
    if (n <= 84 * 52) return "WORLDSIZE_STANDARD";
    if (n <= 104 * 64) return "WORLDSIZE_LARGE";
    return "WORLDSIZE_HUGE";
  }

  /* identical to rivers_core.plotRiverLines -- repeated here so the serializer is standalone.
   * horizontal edge = south edge of tile to its NORTH -> isNOfRiver + RiverWEDirection (E=1,W=3)
   * vertical   edge = east  edge of tile to its WEST  -> isWOfRiver + RiverNSDirection (N=0,S=2) */
  function plotRiverLines(nof, wof, gx, civY, H) {
    const gr = (H - 1) - civY, out = [];
    const n = nof.get(gr + "," + gx), w = wof.get(gr + "," + gx);
    if (n) { out.push("\tisNOfRiver"); out.push("\tRiverWEDirection=" + n.dir); }
    if (w) { out.push("\tisWOfRiver"); out.push("\tRiverNSDirection=" + w.dir); }
    return out;
  }

  /* opts: { W, H, topLat, botLat,                  -- required
   *         players: [{leader,civ,x,y}] = [],      -- x,y already in Civ (south-origin) coords
   *         rivers: {nof,wof} = null,
   *         startYear = -4000, wrapX = 0,
   *         description = 'Generated by Terra-WBS',
   *         randomizeResources = true,             -- vanilla-Europe style; set false once bonuses exist
   *         placeholderPlayers = 18 }              -- seats written when players is empty */
  function serialize(grid, opts) {
    const { W, H, topLat, botLat, rivers } = opts;
    const players = opts.players || [];
    const startYear = opts.startYear != null ? opts.startYear : -4000;
    const wrapX = opts.wrapX ? 1 : 0;
    const desc = opts.description != null ? opts.description : "Generated by Terra-WBS";
    const nSeats = opts.placeholderPlayers != null ? opts.placeholderPlayers : 18;
    const L = [];
    L.push("Version=11", "BeginGame", "\tCalendar=CALENDAR_DEFAULT", "\tGameTurn=0",
      "\tStartYear=" + startYear, "\tDescription=" + desc, "EndGame");
    if (players.length) {
      // BtS always defines all 18 civ slots. Writing only the placed players leaves slots
      // k..17 undefined; the engine then reads empty leader/civ types for them at game init ->
      // findInfoTypeNum returns -1 -> CTD at start (the setup screen still shows the k real civs).
      // Vanilla a_CivSpecificUnits / Earth_IceAge fill the remainder with LeaderType=NONE slots.
      const TOTAL = Math.max(18, players.length);
      for (let i = 0; i < TOTAL; i++) L.push("BeginTeam", "EndTeam");
      for (let i = 0; i < players.length; i++) {
        const p = players[i];
        L.push("BeginPlayer", "\tLeaderType=" + p.leader, "\tCivType=" + p.civ, "\tTeam=" + i,
          "\tPlayableCiv=1", "\tStartingX=" + p.x + ", StartingY=" + p.y,
          "\tHandicap=HANDICAP_NOBLE", "EndPlayer");
      }
      for (let i = players.length; i < TOTAL; i++)
        L.push("BeginPlayer", "\tLeaderType=NONE", "\tCivType=NONE", "\tTeam=" + i, "EndPlayer");
    } else {
      for (let i = 0; i < nSeats; i++)
        L.push("BeginPlayer", "\tLeaderType=NONE", "\tCivType=NONE", "\tTeam=" + i,
          "\tRandomStartLocation=true", "EndPlayer");
    }
    L.push("BeginMap", "\tgrid width=" + W, "\tgrid height=" + H,
      "\twrap X=" + wrapX, "\twrap Y=0",
      "\ttop latitude=" + Math.round(topLat), "\tbottom latitude=" + Math.round(botLat),
      "\tworld size=" + worldSizeFor(W, H), "\tclimate=CLIMATE_TEMPERATE",
      "\tsealevel=SEALEVEL_MEDIUM", "\tnum plots written=" + (W * H));
    if (opts.randomizeResources !== false) L.push("\tRandomize Resources=true");
    L.push("EndMap", "", "### Plot Info ###");
    for (let x = 0; x < W; x++) for (let y = 0; y < H; y++) {
      const t = grid[(H - 1) - y][x];
      L.push("BeginPlot", "\tx=" + x + ",y=" + y);
      if (t.bonus) L.push("\tBonusType=" + t.bonus);   // special-tile resources; kept even with Randomize Resources (addBonuses skips plots that already have one)
      if (t.feature) L.push("\tFeatureType=" + t.feature + ", FeatureVariety=" + (t.fv || 0));
      L.push("\tTerrainType=" + t.terrain, "\tPlotType=" + t.plot);
      if (rivers) { const rl = plotRiverLines(rivers.nof, rivers.wof, x, y, H); for (let q = 0; q < rl.length; q++) L.push(rl[q]); }
      L.push("EndPlot");
    }
    // CRLF line endings: Civ4's WorldBuilder parser is Windows-native and misreads LF-only
    // files -- token boundaries slip, findInfoTypeNum returns -1, and the game CTDs at start.
    // Every WBSave the game ships is CRLF; matching that is required, not cosmetic.
    return L.join("\r\n") + "\r\n";
  }

  const api = { worldSizeFor, plotRiverLines, serialize };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.Civ4WBS = api;
})(typeof globalThis !== "undefined" ? globalThis : this);
